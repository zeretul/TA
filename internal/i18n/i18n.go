package i18n

import (
	"fmt"
	"strings"
)

const (
	LocaleAuto = "auto"
	LocaleZH   = "zh-CN"
	LocaleEN   = "en-US"
)

type Localizer struct {
	locale string
}

func New(locale string) Localizer {
	return Localizer{locale: Resolve(locale)}
}

func FromHeader(value string) Localizer {
	return New(value)
}

func Resolve(value string) string {
	normalized := strings.TrimSpace(value)
	if normalized == "" || strings.EqualFold(normalized, LocaleAuto) {
		return LocaleZH
	}
	lower := strings.ToLower(normalized)
	if strings.HasPrefix(lower, "zh") {
		return LocaleZH
	}
	if strings.HasPrefix(lower, "en") {
		return LocaleEN
	}
	return LocaleZH
}

func (l Localizer) Locale() string {
	return l.locale
}

func (l Localizer) T(key string, args ...any) string {
	catalog := catalogZH
	if l.locale == LocaleEN {
		catalog = catalogEN
	}
	template, ok := catalog[key]
	if !ok {
		template = catalogZH[key]
	}
	if template == "" {
		return key
	}
	return format(template, args...)
}

func format(template string, args ...any) string {
	out := template
	for i := 0; i+1 < len(args); i += 2 {
		name, ok := args[i].(string)
		if !ok || name == "" {
			continue
		}
		out = strings.ReplaceAll(out, "{{"+name+"}}", stringify(args[i+1]))
	}
	return out
}

func stringify(v any) string {
	if s, ok := v.(string); ok {
		return s
	}
	return fmt.Sprint(v)
}

