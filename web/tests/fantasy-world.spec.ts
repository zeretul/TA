import { expect, test } from '@playwright/test'
for (const language of ['zh-CN', 'en-US']) for (const theme of ['dark', 'light']) for (const width of [390, 1440]) {
  test(`fantasy ${language} ${theme} ${width}`, async ({ page }, info) => {
    const english = language === 'en-US'
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.setViewportSize({ width, height: 900 })
    await page.goto(`/tests/fixtures/fantasy-world.html?language=${language}&theme=${theme}&mode=creation`)
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await expect(dialog.getByRole('radiogroup').nth(1).getByRole('radio')).toHaveCount(7)
    await dialog.getByPlaceholder(english ? 'Name your character' : '写下角色的名字').fill('Rowan')
    await dialog.getByRole('radio', { name: new RegExp(english ? 'Borrowed Lamp Apprentice' : '借灯学徒') }).click()
    await page.screenshot({ path: info.outputPath('creation-choices.png') })
    await dialog.getByRole('button', { name: english ? 'Generate identity' : '生成身份', exact: true }).click()
    await expect(dialog).toContainText(english ? 'Learned skills' : '已学技能')
    await expect(dialog).toContainText(english ? 'Candleflame Edge' : '烛焰引锋')
    await expect(dialog).toContainText(english ? 'Silver marks' : '银铢')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('creation-preview.png') })
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('adventure-combat')).toBeVisible()
    await expect(page.getByTestId('adventure-combat')).toContainText(english ? 'Realms encounter' : '诸境交锋')
    await expect(page.getByTestId('adventure-combat')).toContainText(english ? 'Effort' : '精力')
    await page.getByRole('combobox').selectOption('skill:sg-spark')
    await expect(page.getByTestId('adventure-combat')).toContainText(english ? 'Charcoal' : '炭粉')
    await page.screenshot({ path: info.outputPath('combat-costs.png') })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Character ledger', exact: true }).click()
    await expect(page.locator('[data-state-panel-mode]')).toBeVisible()
    await page.screenshot({ path: info.outputPath('ledger.png') })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Runtime artwork', exact: true }).click()
    const gallery = page.getByTestId('runtime-artwork')
    await expect(gallery.locator('img')).toHaveCount(4)
    for (const picture of await gallery.locator('img').all()) await picture.scrollIntoViewIfNeeded()
    await expect.poll(() => gallery.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    await gallery.screenshot({ path: info.outputPath('runtime-artwork.png') })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(await page.evaluate(() => (window as Window & { fantasyFixtureWrites?: string[] }).fantasyFixtureWrites)).toEqual(['identity-preview'])
    expect(errors).toEqual([])
  })
}
